# Integer
a = 10
print("Value of a:", a)
print("Type of a:", type(a))

# Float
b = 5.5
print("\nValue of b:", b)
print("Type of b:", type(b))

# String
name = "Aditya"
print("\nValue of name:", name)
print("Type of name:", type(name))

# Boolean
is_student = True
print("\nValue of is_student:", is_student)
print("Type of is_student:", type(is_student))

# List
numbers = [1, 2, 3, 4]
print("\nValue of numbers:", numbers)
print("Type of numbers:", type(numbers))

# Tuple
coordinates = (10, 20)
print("\nValue of coordinates:", coordinates)
print("Type of coordinates:", type(coordinates))
 

