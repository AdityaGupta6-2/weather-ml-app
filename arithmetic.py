x = 15
y = 4

print("Addition:", x + y)        # 15 + 4 = 19
print("Subtraction:", x - y)     # 15 - 4 = 11
print("Multiplication:", x * y)  # 15 * 4 = 60
print("Division:", x / y)        # 15 / 4 = 3.75
print("Floor Division:", x // y) # 15 // 4 = 3
print("Modulus:", x % y)         # Remainder = 3
print("Exponent:", x ** y)       # 15^4
